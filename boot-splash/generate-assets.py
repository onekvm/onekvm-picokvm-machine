"""Regenerate the checked-in boot screen artwork; not needed on target or by OE.

Writes assets.h for onekvm-boot-splash. With --uboot-header PATH it also writes
the whole boot screen, with an empty bar, for the PicoKVM U-Boot.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

# Keep in step with onekvm-boot-splash.c.
SIZE = 240
TOP = (SIZE - 172) // 2
LOGO_WIDTH, LOGO_Y, CAPTION_Y = 208, TOP + 48, TOP + 125
BAR_WIDTH, BAR_HEIGHT = 160, 4
BAR_X, BAR_Y = (SIZE - BAR_WIDTH) // 2, TOP + 150
BACKGROUND = (8, 11, 17)
CAPTION = (132, 144, 164)
BAR_TRACK, BAR_FILL = (31, 41, 59), (22, 119, 255)


def rgb565(pixel):
    r, g, b = pixel[:3]
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def runs_of(image):
    runs = []
    for pixel in image.getdata():
        color = rgb565(pixel)
        if runs and runs[-1][1] == color and runs[-1][0] < 65535:
            runs[-1][0] += 1
        else:
            runs.append([1, color])
    return runs


def logo():
    mark = Image.open(HERE / "logo.png").convert("RGBA")
    mark = mark.crop(mark.getbbox())
    mark = mark.resize(
        (LOGO_WIDTH, round(LOGO_WIDTH * mark.height / mark.width)), Image.Resampling.LANCZOS
    )
    image = Image.new("RGB", mark.size, BACKGROUND)
    image.paste(mark, (0, 0), mark)
    return image


def caption(text):
    font = ImageFont.truetype(FONT, 12)
    left, top, right, bottom = font.getbbox(text)
    image = Image.new("RGB", (right - left, bottom - top), BACKGROUND)
    ImageDraw.Draw(image).text((-left, -top), text, font=font, fill=CAPTION)
    return image


def bar_pixel(x, y, fill):
    inset = 2 if y in (0, BAR_HEIGHT - 1) else 0
    if inset <= x and x + inset < fill:
        return BAR_FILL
    if inset <= x and x + inset < BAR_WIDTH:
        return BAR_TRACK
    return BACKGROUND


def write_assets(assets):
    lines = [
        "/* SPDX-License-Identifier: MIT */",
        "/* Generated by generate-assets.py; RGB565 run-length encoded artwork. */",
    ]
    for name, image in assets:
        assert 0 < image.width <= SIZE and 0 < image.height <= 172
        runs = runs_of(image)
        lines.append(f"static const uint16_t {name}_runs[] = {{")
        for offset in range(0, len(runs), 6):
            lines.append("    " + ", ".join(f"{n}, 0x{c:04x}" for n, c in runs[offset:offset + 6]) + ",")
        lines.extend((
            "};",
            f"static const struct splash_asset {name} = {{",
            f"    {image.width}, {image.height}, {name}_runs, sizeof({name}_runs) / sizeof(uint16_t)",
            "};",
        ))
    (HERE / "assets.h").write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(assets)} assets to {HERE / 'assets.h'}")


def write_uboot_header(path, assets):
    frame = Image.new("RGB", (SIZE, SIZE), BACKGROUND)
    for image, y in zip((image for _, image in assets), (LOGO_Y, CAPTION_Y)):
        frame.paste(image, ((SIZE - image.width) // 2, y))
    # U-Boot shows the empty bar and fills it while it loads the slot.
    for x in range(BAR_WIDTH):
        for y in range(BAR_HEIGHT):
            frame.putpixel((BAR_X + x, BAR_Y + y), bar_pixel(x, y, 0))
    # The panel runs in its power-on address mode: rows top to bottom, as here.
    runs = runs_of(frame)
    assert sum(n for n, _ in runs) == SIZE * SIZE
    header = [
        "/* SPDX-License-Identifier: GPL-2.0+ */",
        "/* Generated by onekvm-picokvm-machine/boot-splash/generate-assets.py. */",
        "",
        f"#define PICOKVM_LOGO_SIZE\t{SIZE}",
        f"#define PICOKVM_LOGO_RUNS\t{len(runs)}",
        "",
        "/* Boot bar on the 240x240 screen, as onekvm-boot-splash draws it. */",
        f"#define ONEKVM_BAR_X\t\t{BAR_X}",
        f"#define ONEKVM_BAR_Y\t\t{BAR_Y}",
        f"#define ONEKVM_BAR_WIDTH\t{BAR_WIDTH}",
        f"#define ONEKVM_BAR_HEIGHT\t{BAR_HEIGHT}",
        f"#define ONEKVM_BAR_BACKGROUND\t0x{rgb565(BACKGROUND):04x}",
        f"#define ONEKVM_BAR_TRACK\t0x{rgb565(BAR_TRACK):04x}",
        f"#define ONEKVM_BAR_FILL\t\t0x{rgb565(BAR_FILL):04x}",
        "",
        "/* {count, RGB565} runs, row-major. */",
        "static const u16 picokvm_logo_rle[] = {",
    ]
    for offset in range(0, len(runs), 6):
        header.append("\t" + ", ".join(f"{n}, 0x{c:04x}" for n, c in runs[offset:offset + 6]) + ",")
    header.append("};")
    path.write_text("\n".join(header) + "\n")
    print(f"Wrote the U-Boot boot screen to {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uboot-header", type=Path)
    args = parser.parse_args()
    assets = [("logo_boot", logo()), ("starting", caption("Starting up"))]
    write_assets(assets)
    if args.uboot_header:
        write_uboot_header(args.uboot_header, assets)


if __name__ == "__main__":
    main()
